   public static int tier(int count) {
      int tier = 0;

      for (int i = 1; i < TIER_FROM.length; i++) {
         if (count >= TIER_FROM[i]) {
            tier = i;
         }
      }

      return tier;
   }

   public static float damageBonus(int count) {
      if (count <= 0) {
         return 0.0F;
      } else {
         return count < 10 ? 0.01F * (float)count * (float)count / 10.0F : Math.min(0.15F, 0.01F * (float)count);
      }
   }

   public static float shakeMagnitude(float degrees) {
      return degrees / 25.0F;
   }

   public static double launchSpeedFor(double heightBlocks) {
      return Math.sqrt(0.16 * heightBlocks);
   }
