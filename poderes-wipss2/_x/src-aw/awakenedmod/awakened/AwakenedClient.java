   private static void addEntityLayers(AddLayers event) {
      for (Model skin : event.getSkins()) {
         PlayerRenderer renderer = (PlayerRenderer)event.getSkin(skin);
         if (renderer != null) {
            ModelPart belt = event.getEntityModels().bakeLayer(BeltModel.LAYER);
            renderer.addLayer(new BeltRenderLayer(renderer, belt));
            ModelPart gauntlets = event.getEntityModels().bakeLayer(GauntletModel.LAYER);
            renderer.addLayer(new GauntletRenderLayer(renderer, gauntlets));
            ModelPart exoSuit = event.getEntityModels().bakeLayer(ExosavantSuitModel.LAYER);
            ModelPart exoChip = event.getEntityModels().bakeLayer(ExosavantChipModel.LAYER);
            renderer.addLayer(new ExosavantSuitLayer(renderer, exoSuit, exoChip));
            renderer.addLayer(new OverheatRenderLayer(renderer));
            renderer.addLayer(new ReaperFlameLayer(renderer));
            renderer.addLayer(new ExoThrusterLayer(renderer));
            renderer.addLayer(new GammaSkinLayer(renderer));
            renderer.addLayer(new VelocityPhaseLayer(renderer));
            renderer.addLayer(new VelocityChargeLayer(renderer));
            TimelessColdLayer.attach(renderer);
            ChronoBodyLayer.attach(renderer);
            RuinDecayLayer.attach(renderer);
            renderer.addLayer(new PyroFlameLayer(renderer));
            renderer.addLayer(new LimbGlowLayer(renderer));
            renderer.addLayer(new HeadAnchorLayer(renderer));
            renderer.addLayer(new RuinHandLayer(renderer));
         }
      }

      for (EntityType<?> type : event.getEntityTypes()) {
         if (type != EntityType.PLAYER) {
            attachColdLayer(event, type);
         }
      }
   }

   private static <T extends Entity> void attachColdLayer(AddLayers event, EntityType<T> type) {
      if (event.getRenderer(type) instanceof LivingEntityRenderer<?, ?> living) {
         TimelessColdLayer.attach(living);
         ChronoBodyLayer.attach(living);
         RuinDecayLayer.attach(living);
      }
   }
